// Precompiles blog posts at build time so pages can serve them on
// Cloudflare Workers without fs access or `new Function` at request time.
// Run before `next build` / `opennextjs-cloudflare build`.
// Output: src/content/generated-posts.ts
import fs from 'fs'
import path from 'path'
import matter from 'gray-matter'
import { remark } from 'remark'
import remarkRehype from 'remark-rehype'
import rehypeStringify from 'rehype-stringify'
import remarkGfm from 'remark-gfm'
import prism from 'remark-prism'

const BLOG_DIR = path.join(process.cwd(), 'content', 'blog')
const OUT_FILE = path.join(
  process.cwd(),
  'src',
  'content',
  'generated-posts.ts',
)
const LOCALES = ['pt', 'en']

const slugs = fs.readdirSync(BLOG_DIR).filter((d) => {
  const full = path.join(BLOG_DIR, d)
  return (
    fs.statSync(full).isDirectory() &&
    LOCALES.some((l) => fs.existsSync(path.join(full, `index.${l}.mdx`)))
  )
})

async function markdownToHtml(content) {
  const file = await remark()
    .use(remarkGfm)
    .use(prism)
    .use(remarkRehype, { allowDangerousHtml: true })
    .use(rehypeStringify, { allowDangerousHtml: true })
    .process(content)
  return String(file)
}

const posts = {}

for (const locale of LOCALES) {
  posts[locale] = {}
  for (const slug of slugs) {
    const file = path.join(BLOG_DIR, slug, `index.${locale}.mdx`)
    if (!fs.existsSync(file)) continue
    const raw = fs.readFileSync(file, 'utf8')
    const { content, data } = matter(raw)
    const html = await markdownToHtml(content)
    posts[locale][slug] = { html, data }
  }
}

// Sorted slug lists per locale (by date)
const sorted = {}
for (const locale of LOCALES) {
  sorted[locale] = Object.entries(posts[locale])
    .map(([slug, p]) => ({ slug, date: p.data.date || '' }))
    .sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0))
    .map((p) => p.slug)
}

const out = `// AUTO-GENERATED by scripts/build-content.mjs — do not edit.
export const generatedPosts = ${JSON.stringify(posts)} as const;
export const sortedSlugs: Record<string, string[]> = ${JSON.stringify(sorted)};
export const allSlugs: string[] = ${JSON.stringify(slugs)};
`

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
fs.writeFileSync(OUT_FILE, out)
console.log(`generated ${slugs.length} posts -> ${OUT_FILE}`)
